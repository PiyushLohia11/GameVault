-- ========================================================
-- GameVault Schema & Sample Data for H2 (Oracle Mode)
-- Automatically loaded on startup when using H2
-- ========================================================

CREATE SCHEMA IF NOT EXISTS SYSTEM;
SET SCHEMA SYSTEM;

-- 1. DEVELOPER Table
CREATE TABLE IF NOT EXISTS SYSTEM.DEVELOPER (
    DEVELOPER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DEVELOPER_NAME VARCHAR2(120)
);

-- 2. GENRE Table
CREATE TABLE IF NOT EXISTS SYSTEM.GENRE (
    GENRE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    GENRE_NAME VARCHAR2(80)
);

-- 3. PLATFORM Table
CREATE TABLE IF NOT EXISTS SYSTEM.PLATFORM (
    PLATFORM_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PLATFORM_NAME VARCHAR2(80)
);

-- 4. USERS Table
CREATE TABLE IF NOT EXISTS SYSTEM.USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50),
    EMAIL VARCHAR2(254)
);

-- 5. GAME Table
CREATE TABLE IF NOT EXISTS SYSTEM.GAME (
    GAME_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE VARCHAR2(200),
    DEVELOPER_ID NUMBER,
    RELEASE_YEAR NUMBER(4,0)
);

-- 6. GAME_GENRE Table
CREATE TABLE IF NOT EXISTS SYSTEM.GAME_GENRE (
    GAME_ID NUMBER,
    GENRE_ID NUMBER
);

-- 7. GAME_PLATFORM Table
CREATE TABLE IF NOT EXISTS SYSTEM.GAME_PLATFORM (
    GAME_ID NUMBER,
    PLATFORM_ID NUMBER
);

-- 8. ACHIEVEMENT Table
CREATE TABLE IF NOT EXISTS SYSTEM.ACHIEVEMENT (
    ACHIEVEMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    GAME_ID NUMBER,
    ACHIEVEMENT_NAME VARCHAR2(160),
    DESCRIPTION VARCHAR2(1000),
    POINTS NUMBER(6,0) DEFAULT 0
);

-- 9. USER_ACHIEVEMENT Table
CREATE TABLE IF NOT EXISTS SYSTEM.USER_ACHIEVEMENT (
    USER_ID NUMBER,
    ACHIEVEMENT_ID NUMBER,
    UNLOCK_DATE DATE DEFAULT CURRENT_DATE
);

-- 10. USER_GAME Table
CREATE TABLE IF NOT EXISTS SYSTEM.USER_GAME (
    USER_ID NUMBER,
    GAME_ID NUMBER,
    PLATFORM_ID NUMBER,
    STATUS VARCHAR2(20) DEFAULT 'Backlog',
    PLAYTIME_HRS NUMBER(8,1) DEFAULT 0,
    LAST_PLAYED DATE
);

-- 11. REVIEW Table
CREATE TABLE IF NOT EXISTS SYSTEM.REVIEW (
    USER_ID NUMBER,
    GAME_ID NUMBER,
    RATING NUMBER(2,0),
    REVIEW_TEXT VARCHAR2(2000),
    REVIEW_DATE DATE DEFAULT CURRENT_DATE
);

-- 12. FRIENDSHIP Table
CREATE TABLE IF NOT EXISTS SYSTEM.FRIENDSHIP (
    USER_ID NUMBER,
    FRIEND_ID NUMBER,
    SINCE_DATE DATE DEFAULT CURRENT_DATE
);

